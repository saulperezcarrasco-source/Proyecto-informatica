"""Clip the offline map coverage and walking graph to Dominican Republic.

Uses the OSM national boundary relation, not a longitude cut through Haiti.
Requires osmium==4.3.0, shapely==2.1.2 and numpy. See README.md.
"""
from pathlib import Path
import gzip
import hashlib
import json
import struct
import xml.etree.ElementTree as ET

import numpy as np
import osmium
import shapely

ROOT = Path(__file__).resolve().parent
PROJECT = ROOT.parent.parent
BOUNDARY = ROOT / 'boundary.osm'
NATIONAL = PROJECT / 'assets/national'
ROUTING = PROJECT / 'assets/routing'
CACHE = PROJECT / 'tools/island_routing/cache'


class Boundary(osmium.SimpleHandler):
    def __init__(self):
        super().__init__()
        self.geometry = None

    def area(self, area):
        if not area.from_way() and area.orig_id() == 307828:
            self.geometry = shapely.geometry.shape(json.loads(
                osmium.geom.GeoJSONFactory().create_multipolygon(area)))


def main():
    boundary = Boundary()
    boundary.apply_file(str(BOUNDARY), locations=True, idx='flex_mem')
    geometry = boundary.geometry
    if geometry is None or not geometry.is_valid:
        raise RuntimeError('The OSM Dominican national boundary did not assemble')
    shapely.prepare(geometry)
    relation = ET.parse(BOUNDARY).getroot().find("relation[@id='307828']")
    props = dict(name='República Dominicana', osmRelation=307828,
                 source='https://api.openstreetmap.org/api/0.6/relation/307828/full',
                 version=relation.attrib['version'], timestamp=relation.attrib['timestamp'],
                 sourceSha256=hashlib.sha256(BOUNDARY.read_bytes()).hexdigest(),
                 license='ODbL 1.0', attribution='© OpenStreetMap contributors')
    geojson = dict(type='Feature', properties=props, geometry=shapely.geometry.mapping(geometry))
    (NATIONAL / 'dominican-republic.geojson').write_text(json.dumps(geojson,ensure_ascii=False),encoding='utf-8')
    polygons = list(geometry.geoms) if geometry.geom_type == 'MultiPolygon' else [geometry]
    if any(p.interiors for p in polygons):
        raise RuntimeError('Boundary contains holes: extend selection/masking before preparing')
    rings = [list(p.exterior.coords) for p in polygons]
    generated = ['// Generated by tools/dominican_region/prepare.py from OSM relation 307828.',
                 '// © OpenStreetMap contributors, ODbL 1.0. Records are (latitude, longitude).',
                 'const dominicanBoundary = <List<(double, double)>>[']
    for ring in rings:
        generated.append('  [')
        generated.extend(f'    ({lat:.7f}, {lon:.7f}),' for lon,lat in ring)
        generated.append('  ],')
    generated.append('];\n')
    (PROJECT / 'lib/core/dominican_boundary.dart').write_text('\n'.join(generated),encoding='utf-8')
    print(f'Boundary: {geometry.bounds}, {len(rings)} polygons, {sum(map(len,rings))} vertices',flush=True)

    raw = gzip.decompress((CACHE / 'island-walking.rdi').read_bytes())
    magic,n,m = struct.unpack_from('<4sII',raw)
    if magic != b'RDI1':
        raise RuntimeError('Invalid intermediate graph')
    offset = 12
    coords = np.frombuffer(raw,dtype='<i4',count=2*n,offset=offset).reshape(n,2)
    offset += 8*n
    offsets = np.frombuffer(raw,dtype='<u4',count=n+1,offset=offset)
    offset += 4*(n+1)
    targets = np.frombuffer(raw,dtype='<u4',count=m,offset=offset)
    offset += 4*m
    weights = np.frombuffer(raw,dtype='<f4',count=m,offset=offset)
    allowed = shapely.intersects_xy(geometry,coords[:,1]/1e7,coords[:,0]/1e7)
    # Keep the asset within the map archive's existing latitude extent too.
    allowed &= (coords[:,0]>=173000000) & (coords[:,0]<=201000000)
    allowed &= (coords[:,1]>=-720500000) & (coords[:,1]<=-682000000)
    sources = np.repeat(np.arange(n,dtype=np.uint32),np.diff(offsets))
    keep = allowed[sources] & allowed[targets]
    ids = np.flatnonzero(keep)
    for start in range(0,len(ids),50000):
        batch = ids[start:start+50000]
        points = np.stack((coords[sources[batch]][:,::-1],coords[targets[batch]][:,::-1]),axis=1)/1e7
        keep[batch] = shapely.covers(geometry,shapely.linestrings(points))
    used = np.zeros(n,dtype=bool)
    used[sources[keep]] = True
    used[targets[keep]] = True
    mapping = np.full(n,-1,dtype=np.int32)
    count = int(used.sum())
    mapping[used] = np.arange(count,dtype=np.int32)
    new_sources = mapping[sources[keep]]
    new_targets = mapping[targets[keep]].astype('<u4')
    new_weights = weights[keep]
    new_coords = coords[used]
    new_offsets = np.zeros(count+1,dtype='<u4')
    new_offsets[1:] = np.cumsum(np.bincount(new_sources,minlength=count),dtype=np.uint32)
    parent = list(range(count))
    def root(i):
        while parent[i]!=i:
            parent[i]=parent[parent[i]]
            i=parent[i]
        return i
    for a,b in zip(new_sources,new_targets):
        ra,rb=root(int(a)),root(int(b))
        if ra!=rb: parent[rb]=ra
    components = np.fromiter((root(i) for i in range(count)),dtype='<u4',count=count)
    result = ROUTING / 'dominican-walking.rdi'
    with result.open('wb') as output, gzip.GzipFile(fileobj=output,mode='wb',mtime=0,filename='') as stream:
        stream.write(struct.pack('<4sII',b'RDI1',count,len(new_targets)))
        for section in (new_coords,new_offsets,new_targets,new_weights,components):
            stream.write(section.tobytes())
    _,counts = np.unique(components,return_counts=True)
    manifest = dict(name='Red peatonal de República Dominicana',
        source='https://download.geofabrik.de/central-america/haiti-and-domrep-261118.osm.pbf',
        boundary=props, format='RDI1 little-endian, gzip', nodes=count,directedEdges=len(new_targets),
        bytes=result.stat().st_size,sha256=hashlib.sha256(result.read_bytes()).hexdigest(),
        weakComponents=sorted(counts.tolist(),reverse=True),
        attribution='© OpenStreetMap contributors; Geofabrik extract; ODbL 1.0',
        policy='Only nodes in Dominican Republic and segments fully covered by its national boundary. Original walking access/direction filters preserved. No synthetic edges.',
        limitations='Not field verified. Snap approaches are separate, unverified accesses. No ferries or real-time information.')
    (ROUTING / 'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    print(json.dumps({k:manifest[k] for k in ('nodes','directedEdges','bytes','sha256')},indent=2),flush=True)


if __name__=='__main__': main()
